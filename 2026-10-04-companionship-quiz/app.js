let currentChoice=null;
const quizView=document.getElementById("quiz-view");
const resultView=document.getElementById("result-view");
const title=document.getElementById("result-title");
function showResult(choice){
 if(typeof choice!=="string"||!Object.prototype.hasOwnProperty.call(RESULTS,choice)){
  throw new Error("請選擇 A B C 或 D");
 }
 const data=RESULTS[choice];
 document.getElementById("result-choice").textContent=choice+"｜"+data.object;
 title.textContent=data.title;
 document.getElementById("result-lead").textContent=data.lead.replace(/\n/g,"，");
 const body=document.getElementById("result-body");
 body.replaceChildren();
 data.sections.forEach(section=>{
  const el=document.createElement("section");
  el.className="result-block"+(section.className?" "+section.className:"");
  const heading=document.createElement("h2");
  heading.textContent=section.heading;el.append(heading);
  section.paragraphs.forEach(text=>{
   const paragraph=document.createElement("p");
   paragraph.textContent=section.className==="quote"?text:text.replace(/\n/g,"，");
   el.append(paragraph);
  });
  body.append(el);
 });
 currentChoice=choice;quizView.hidden=true;resultView.hidden=false;
 window.scrollTo({top:0,behavior:"auto"});
 title.focus({preventScroll:true});
 return {choice,object:data.object,title:data.title,sections:data.sections};
}
function resetQuiz(){
 currentChoice=null;resultView.hidden=true;quizView.hidden=false;
 window.scrollTo({top:0,behavior:"auto"});
 const first=document.querySelector("[data-choice]");
 first.focus({preventScroll:true});
}
document.querySelectorAll("[data-choice]").forEach(button=>{
 button.addEventListener("click",()=>showResult(button.dataset.choice));
});
document.getElementById("reset").addEventListener("click",resetQuiz);
